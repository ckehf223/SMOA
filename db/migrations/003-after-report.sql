-- 사후 보고의 독립 테이블. 기존 업무 테이블이나 프로그램 설정을 변경하지 않는다.
CREATE TABLE IF NOT EXISTS AFTRPT (
    REPORT_ID bigint unsigned NOT NULL AUTO_INCREMENT,
    LIB_ID varchar(60) NOT NULL,
    ORG_MSTR_CODE varchar(64) NOT NULL,
    ORG_CODE varchar(64) NOT NULL,
    ACTIVITY_DATE date NOT NULL,
    SLOT_CODE varchar(10) NOT NULL,
    REPORT_ROLE varchar(11) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ORGANIZER_ONCE tinyint GENERATED ALWAYS AS
        (CASE WHEN REPORT_ROLE = 'ORGANIZER' THEN 1 ELSE NULL END) STORED,
    REPORT_TOKEN char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    REPORT_ENC text NOT NULL,
    SYS_RUSR_ID varchar(64) NOT NULL,
    SYS_RUSR_DTTM datetime(6) NOT NULL,
    SYS_MUSR_ID varchar(64) NOT NULL,
    SYS_MUSR_DTTM datetime(6) NOT NULL,
    PRIMARY KEY (REPORT_ID),
    UNIQUE KEY UQ_AFTRPT_ORGANIZER (LIB_ID, ORG_MSTR_CODE, ORG_CODE, ACTIVITY_DATE, SLOT_CODE, ORGANIZER_ONCE),
    KEY IX_AFTRPT_DATE (LIB_ID, ACTIVITY_DATE, REPORT_ROLE, REPORT_ID),
    CONSTRAINT CK_AFTRPT_ROLE CHECK (REPORT_ROLE IN ('ORGANIZER', 'PARTICIPANT')),
    CONSTRAINT CK_AFTRPT_SLOT CHECK (SLOT_CODE IN ('1타임', '2타임', '3타임', '4타임', '그 외'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
COMMENT='타임별 주관자 보고와 개별 활동자 보고';
